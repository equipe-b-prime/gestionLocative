-- Vue 1 : Synthèse financière par bail
CREATE OR REPLACE VIEW public.v_bail_financier AS
SELECT
    b.id AS bail_id,
    COUNT(q.id) AS nb_quittances,
    COALESCE(SUM(q.montant_loyer_facture + q.montant_charge_facture), 0::numeric) AS total_facture,
    COALESCE(SUM(pa.total_paye), 0::numeric) AS total_encaisse,
    COALESCE(SUM(q.montant_loyer_facture + q.montant_charge_facture), 0::numeric) - COALESCE(SUM(pa.total_paye), 0::numeric) AS reste_du,
    COUNT(q.id) FILTER (WHERE COALESCE(pa.total_paye, 0::numeric) = 0::numeric) AS nb_quittances_non_payees,
    MAX(q.mois) AS dernier_mois_facture,
    MAX(pa.dernier_paiement) AS dernier_paiement
FROM bail b
LEFT JOIN quittance q ON q.bail_id = b.id
LEFT JOIN (
    SELECT
        p.quittance_id,
        SUM(p.montant_paye) AS total_paye,
        MAX(p.date_paiement) AS dernier_paiement
    FROM paiement p
    GROUP BY p.quittance_id
) pa ON pa.quittance_id = q.id
GROUP BY b.id;

-- Vue 2 : Situation globale par locataire
CREATE OR REPLACE VIEW public.v_locataire_situation AS
SELECT
    l.id AS locataire_id,
    COUNT(DISTINCT b.id) AS nb_baux,
    COUNT(DISTINCT b.id) FILTER (WHERE CURRENT_DATE >= b.date_debut AND CURRENT_DATE <= b.date_fin) AS nb_baux_actifs,
    COALESCE(SUM(bf.nb_quittances), 0::numeric)::bigint AS nb_quittances,
    COALESCE(SUM(bf.total_facture), 0::numeric) AS total_facture,
    COALESCE(SUM(bf.total_encaisse), 0::numeric) AS total_encaisse,
    COALESCE(SUM(bf.reste_du), 0::numeric) AS reste_du,
    COALESCE(SUM(bf.nb_quittances_non_payees), 0::numeric)::bigint AS nb_quittances_non_payees,
    MIN(b.date_debut) AS premier_bail,
    MAX(bf.dernier_paiement) AS dernier_paiement
FROM locataire l
LEFT JOIN bail b ON b.locataire_id = l.id
LEFT JOIN v_bail_financier bf ON bf.bail_id = b.id
GROUP BY l.id;

-- Vue 3 : Reconstitution des périodes d'occupation et vacance par appartement
CREATE OR REPLACE VIEW public.v_periode_occupation AS
WITH baux AS (
    SELECT
        b.appartement_id,
        b.date_debut::date AS date_debut,
        b.date_fin::date AS date_fin,
        b.montant_loyer,
        (l.nom::text || ' '::text) || l.prenom::text AS locataire_nom
    FROM bail b
    LEFT JOIN locataire l ON l.id = b.locataire_id
    WHERE b.date_cloture IS NULL
), bornes AS (
    SELECT
        a.id AS appartement_id,
        a.immeuble_id,
        i.nom AS immeuble_nom,
        a.surface,
        a.date_creation::date AS date_creation,
        MIN(b.date_debut) AS premier_debut,
        MAX(b.date_fin) AS dernier_fin,
        bool_or(b.date_fin IS NULL) AS bail_ouvert,
        COUNT(b.date_debut) AS nb_baux
    FROM appartement a
    JOIN immeuble i ON i.id = a.immeuble_id
    LEFT JOIN baux b ON b.appartement_id = a.id
    GROUP BY a.id, a.immeuble_id, i.nom, a.surface, a.date_creation
), dernier_loyer AS (
    SELECT DISTINCT ON (baux.appartement_id)
        baux.appartement_id,
        baux.montant_loyer
    FROM baux
    ORDER BY baux.appartement_id, baux.date_debut DESC
), periods AS (
    SELECT
        b.appartement_id,
        b.date_debut,
        b.date_fin,
        b.locataire_nom,
        b.montant_loyer,
        true AS occupe
    FROM baux b
    UNION ALL
    SELECT
        e.appartement_id,
        e.date_fin + 1,
        e.suivant_debut - 1,
        NULL::text AS text,
        NULL::numeric AS "numeric",
        false
    FROM (
        SELECT
            baux.appartement_id,
            baux.date_fin,
            lead(baux.date_debut) OVER (PARTITION BY baux.appartement_id ORDER BY baux.date_debut) AS suivant_debut
        FROM baux
    ) e
    WHERE e.date_fin IS NOT NULL AND e.suivant_debut IS NOT NULL AND e.suivant_debut > (e.date_fin + 1)
    UNION ALL
    SELECT
        bo_1.appartement_id,
        bo_1.date_creation,
        bo_1.premier_debut - 1,
        NULL::text AS text,
        NULL::numeric AS "numeric",
        false
    FROM bornes bo_1
    WHERE bo_1.nb_baux > 0 AND bo_1.date_creation < bo_1.premier_debut
    UNION ALL
    SELECT
        bo_1.appartement_id,
        bo_1.dernier_fin + 1,
        NULL::date AS date,
        NULL::text AS text,
        NULL::numeric AS "numeric",
        false
    FROM bornes bo_1
    WHERE bo_1.nb_baux > 0 AND NOT COALESCE(bo_1.bail_ouvert, false) AND bo_1.dernier_fin IS NOT NULL
    UNION ALL
    SELECT
        bo_1.appartement_id,
        bo_1.date_creation,
        NULL::date AS date,
        NULL::text AS text,
        NULL::numeric AS "numeric",
        false
    FROM bornes bo_1
    WHERE bo_1.nb_baux = 0
)
SELECT
    ROW_NUMBER() OVER (ORDER BY p.appartement_id, p.date_debut) AS periode_id,
    p.appartement_id,
    bo.immeuble_id,
    bo.immeuble_nom,
    bo.surface,
    p.occupe,
    p.date_debut,
    p.date_fin,
    p.locataire_nom,
    p.montant_loyer,
    COALESCE(dl.montant_loyer, 0::numeric) AS dernier_loyer
FROM periods p
JOIN bornes bo ON bo.appartement_id = p.appartement_id
LEFT JOIN dernier_loyer dl ON dl.appartement_id = p.appartement_id
ORDER BY p.appartement_id, p.date_debut;

-- Vue 4 : Revenu mensuel ventilé par bail au prorata des jours
CREATE OR REPLACE VIEW public.v_revenu_bail_mensuel AS
WITH baux AS (
    SELECT
        b.id AS bail_id,
        b.appartement_id,
        a.immeuble_id,
        a.surface,
        b.montant_loyer,
        b.date_debut::date AS debut,
        b.date_fin::date AS fin
    FROM bail b
    JOIN appartement a ON a.id = b.appartement_id
    WHERE b.date_cloture IS NULL
), mois_baux AS (
    SELECT
        ba.bail_id,
        ba.appartement_id,
        ba.immeuble_id,
        ba.surface,
        ba.montant_loyer,
        ba.debut,
        ba.fin,
        m.mois::date AS mois,
        (m.mois + '1 mon'::interval - '1 day'::interval)::date AS mois_fin
    FROM baux ba
    CROSS JOIN LATERAL generate_series(
        date_trunc('month'::text, ba.debut::timestamp with time zone),
        date_trunc('month'::text, COALESCE(ba.fin, GREATEST(ba.debut, CURRENT_DATE))::timestamp with time zone),
        '1 mon'::interval
    ) m(mois)
), calc AS (
    SELECT
        mb.bail_id,
        mb.appartement_id,
        mb.immeuble_id,
        mb.surface,
        mb.montant_loyer,
        mb.mois,
        EXTRACT(DAY FROM mb.mois_fin)::integer AS jours_mois,
        GREATEST(0, LEAST(COALESCE(mb.fin, mb.mois_fin), mb.mois_fin) - GREATEST(mb.debut, mb.mois) + 1) AS jours_bail
    FROM mois_baux mb
)
SELECT
    ROW_NUMBER() OVER (ORDER BY bail_id, mois) AS ligne_id,
    bail_id,
    appartement_id,
    immeuble_id,
    surface,
    mois,
    montant_loyer,
    jours_mois,
    jours_bail,
    ROUND(montant_loyer * jours_bail::numeric / jours_mois::numeric)::numeric(38,1) AS apport_partiel
FROM calc
WHERE jours_bail > 0
ORDER BY bail_id, mois;
