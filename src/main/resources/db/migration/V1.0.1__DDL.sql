-- 1.1 Propriétaire
CREATE TABLE IF NOT EXISTS proprietaire (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    numero VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    adresse VARCHAR(255),
    CONSTRAINT uk_proprietaire_email UNIQUE (email)
);

-- 1.2 Immeuble
CREATE TABLE IF NOT EXISTS immeuble (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    adresse VARCHAR(50) NOT NULL,
    nb_etages INTEGER,
    proprietaire_id BIGINT,
    CONSTRAINT uk_immeuble_nom_adresse UNIQUE (nom, adresse),
    CONSTRAINT fk_immeuble_proprietaire FOREIGN KEY (proprietaire_id) REFERENCES proprietaire(id)
);

-- 1.3 Locataire
CREATE TABLE IF NOT EXISTS locataire (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    numero VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    CONSTRAINT uk_locataire_email UNIQUE (email)
);

-- 1.4 Appartement
CREATE TABLE IF NOT EXISTS appartement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(255),
    surface NUMERIC(38, 2),
    nb_pieces INTEGER,
    etage INTEGER NOT NULL,
    immeuble_id BIGINT,
    proprietaire_id BIGINT,
    date_creation TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_appartement_nom_immeuble UNIQUE (nom, immeuble_id),
    CONSTRAINT fk_appartement_immeuble FOREIGN KEY (immeuble_id) REFERENCES immeuble(id),
    CONSTRAINT fk_appartement_proprietaire FOREIGN KEY (proprietaire_id) REFERENCES proprietaire(id)
);

-- 1.5 Bail
CREATE TABLE IF NOT EXISTS bail (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_debut TIMESTAMP(6) WITHOUT TIME ZONE,
    date_fin TIMESTAMP(6) WITHOUT TIME ZONE,
    montant_loyer NUMERIC(38, 2),
    provision_charges NUMERIC(38, 2) DEFAULT 0,
    depot_garantie NUMERIC(38, 2) DEFAULT 0,
    date_cloture TIMESTAMP(6) WITHOUT TIME ZONE,
    statut VARCHAR(255) DEFAULT 'ACTIF',
    appartement_id BIGINT,
    locataire_id BIGINT,
    CONSTRAINT bail_statut_check CHECK (statut IN ('ACTIF', 'RESILIE', 'TERMINE')),
    CONSTRAINT fk_bail_appartement FOREIGN KEY (appartement_id) REFERENCES appartement(id),
    CONSTRAINT fk_bail_locataire FOREIGN KEY (locataire_id) REFERENCES locataire(id)
);

-- 1.6 Bail Historique
CREATE TABLE IF NOT EXISTS bail_historique (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bail_id BIGINT NOT NULL,
    type VARCHAR(255) NOT NULL,
    ancienne_date_fin TIMESTAMP(6) WITHOUT TIME ZONE,
    nouvelle_date_fin TIMESTAMP(6) WITHOUT TIME ZONE,
    date_operation TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_bail_historique_bail FOREIGN KEY (bail_id) REFERENCES bail(id)
);

-- 1.7 Révision du loyer
CREATE TABLE IF NOT EXISTS revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bail_id BIGINT NOT NULL,
    date_effet TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    montant_loyer NUMERIC(19, 2) NOT NULL,
    CONSTRAINT fk_revision_bail FOREIGN KEY (bail_id) REFERENCES bail(id)
);

-- 1.8 Charges annuelles de l'immeuble
CREATE TABLE IF NOT EXISTS charge (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annee INTEGER NOT NULL,
    montant NUMERIC(38, 2),
    immeuble_id BIGINT,
    CONSTRAINT fk_charge_immeuble FOREIGN KEY (immeuble_id) REFERENCES immeuble(id)
);

-- 1.9 Type de constat
CREATE TABLE IF NOT EXISTS type_constat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(255) NOT NULL,
    CONSTRAINT uk_type_constat_libelle UNIQUE (libelle)
);

-- 1.10 État des lieux
CREATE TABLE IF NOT EXISTS etat_les_lieux (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cout_reparation NUMERIC(38, 2),
    date_constat TIMESTAMP(6) WITHOUT TIME ZONE,
    observations TEXT,
    bail_id BIGINT,
    type_constat_id BIGINT,
    CONSTRAINT fk_etat_les_lieux_bail FOREIGN KEY (bail_id) REFERENCES bail(id),
    CONSTRAINT fk_etat_les_lieux_type FOREIGN KEY (type_constat_id) REFERENCES type_constat(id)
);

-- 1.11 Quittance de loyer
CREATE TABLE IF NOT EXISTS quittance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mois INTEGER NOT NULL,
    annee INTEGER NOT NULL,
    montant_loyer_facture NUMERIC(38, 2) NOT NULL,
    montant_charge_facture NUMERIC(38, 2) NOT NULL,
    bail_id BIGINT,
    CONSTRAINT fk_quittance_bail FOREIGN KEY (bail_id) REFERENCES bail(id)
);

-- 1.12 Paiement
CREATE TABLE IF NOT EXISTS paiement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_paiement TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
    montant_paye NUMERIC(38, 2),
    quittance_id BIGINT,
    CONSTRAINT fk_paiement_quittance FOREIGN KEY (quittance_id) REFERENCES quittance(id)
);

